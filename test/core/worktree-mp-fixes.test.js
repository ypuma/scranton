import './isolation-test-root.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createHash, randomUUID } from 'node:crypto';
import { WorktreeManager } from '../../src/core/worktree.js';
test('integration reclaims recycled PID after age bound, but never steals a live holder token', { timeout: 15000 }, async (t) => {
  const base = path.resolve('.scratch/mp-fix-backend'); fs.mkdirSync(base, { recursive: true });
  const dir = fs.mkdtempSync(path.join(base, 'lock-')); t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  t.mock.method(os, 'tmpdir', () => dir);
  const ws = path.join(dir, 'ws'); fs.mkdirSync(ws);
  const manager = new WorktreeManager({ workspace: ws, hiveDir: path.join(dir, 'hive'), runId: 'test' });
  await manager.init(); t.after(() => manager.close());
  await manager.createWorktree({ agent: 'dwight', milestoneId: 'm1' });
  await manager.snapshotWorktree({ agent: 'dwight', milestoneId: 'm1' }); await manager.createQaWorktree({ milestoneId: 'm1' });
  const real = fs.realpathSync.native(ws), key = createHash('sha256').update(process.platform === 'win32' ? real.toLowerCase() : real).digest('hex').slice(0, 16);
  const lock = path.join(dir, 'scranton-locks', `${key}.lock`); fs.mkdirSync(lock, { recursive: true });
  const owner = path.join(lock, `${process.pid}-${randomUUID()}.json`);
  fs.writeFileSync(owner, JSON.stringify({ pid: process.pid, createdAt: new Date(0).toISOString() }));
  fs.utimesSync(lock, new Date(0), new Date(0));
  await manager.integrateToTarget({ milestoneId: 'm1' });
  fs.mkdirSync(lock); const token = JSON.stringify({ pid: process.pid, createdAt: new Date().toISOString(), token: 'live' });
  fs.writeFileSync(owner, token); fs.utimesSync(lock, new Date(0), new Date(0));
  let preserved = false;
  const timer = setTimeout(() => { preserved = fs.readFileSync(owner, 'utf8') === token; fs.rmSync(lock, { recursive: true }); }, 100);
  t.after(() => clearTimeout(timer));
  await manager.integrateToTarget({ milestoneId: 'm1' }); assert.equal(preserved, true);
});
